// 作息时段：解析 / 判定 / 校验。纯函数，方便离线单测。
//
// 数据源（与 speak-up 共用同一个文件）：`$DSH_HOME/qiyu/schedule.json`
//
//   {
//     "时段": [
//       { "名": "休息", "起": "00:00", "止": "08:30" },
//       { "名": "惰性", "起": "08:30", "止": "19:30" }
//     ]
//   }
//
// 没写的那段 = 活跃。支持跨午夜（比如休息 23:00–07:00）。

/** "HH:MM" → 当天第几分钟（0–1439）；不合法返回 null */
export function 解时分(v) {
  // 宽进：8:5 / 08:05 都认；严出：结果一律按分钟算
  const m = /^(\d{1,2}):(\d{1,2})$/.exec(String(v == null ? '' : v).trim())
  if (!m) return null
  const h = Number(m[1])
  const mm = Number(m[2])
  if (!(h >= 0 && h <= 23) || !(mm >= 0 && mm <= 59)) return null
  return h * 60 + mm
}

/** 分钟数 → "HH:MM" */
export function 成分(分) {
  const n = ((Math.round(Number(分) || 0) % 1440) + 1440) % 1440
  return String(Math.floor(n / 60)).padStart(2, '0') + ':' + String(n % 60).padStart(2, '0')
}

/** 一段时长（分钟），支持跨午夜 */
export function 时长(起, 止) {
  return ((止 - 起) % 1440 + 1440) % 1440
}

/** 某一刻（当天第几分钟）是否落在 [起, 止) 里，支持跨午夜 */
export function 在区间(分, 起, 止) {
  if (起 === 止) return false
  if (起 < 止) return 分 >= 起 && 分 < 止
  return 分 >= 起 || 分 < 止
}

/** 默认作息（和桥原来的硬编码一致） */
export const 默认作息 = {
  休息: { 起: 0, 止: 8 * 60 + 30 },
  惰性: { 起: 8 * 60 + 30, 止: 19 * 60 + 30 },
}

/**
 * DeepSeek API 的**峰时**窗口（北京时间），谷时是它的补集。
 *
 * 口径来源：DeepSeek API 2026-08-23 起生效的新峰谷表（媒体转述原文）：
 *   · 高峰：周一至周五 09:00–12:00、14:00–18:00（UTC+8）
 *   · 闲时：周一至周五 12:01–13:59、18:01 以后，以及周六周日全天
 *
 * ⚠ 峰谷**窗口**是账号级的，跟具体模型无关；具体单价随模型不同
 *   （每个模型有自己的计费表，比如 V4.1-Flash-1017 和 V4 Pro / V4 Flash 就不是一张表，别混用）。
 *   规则只关心一件事：峰时那两段里她不能是"活跃"，否则每条群消息都会叫她、按峰时价烧 token。
 *
 * ⚠ 作息表没有"星期几"这一维 —— 只要某一段落进这两个窗口，工作日里它就是峰时，校验按这个来。
 */
export const 峰时窗口 = [
  { 起: 9 * 60, 止: 12 * 60 },   // 09:00–12:00
  { 起: 14 * 60, 止: 18 * 60 },  // 14:00–18:00
]

/** 某一刻是否落在峰时窗口里（不考虑星期几，保守按"可能是工作日"算） */
export function 在峰时(分) {
  return 峰时窗口.some((w) => 在区间(分, w.起, w.止))
}

/** 把一组"活跃分钟"压成可读的时段串，比如 "09:00–10:30、15:00–16:00" */
export function 拼时段(分钟们) {
  const 排 = [...new Set(分钟们)].sort((a, b) => a - b)
  if (!排.length) return ''
  const 段 = []
  let 起 = 排[0]
  let 上 = 排[0]
  for (const m of 排.slice(1)) {
    if (m === 上 + 1) { 上 = m; continue }
    段.push([起, 上])
    起 = m
    上 = m
  }
  段.push([起, 上])
  return 段.map(([a, b]) => `${成分(a)}–${成分(b + 1)}`).join('、')
}

/**
 * 把 schedule.json 解析成 { 休息:{起,止}, 惰性:{起,止} }（分钟）。
 * 缺的/坏的段用默认值兜底 —— 绝不能因为文件写坏了就没作息。
 */
export function 解析时段(j) {
  const 结果 = {
    休息: { ...默认作息.休息 },
    惰性: { ...默认作息.惰性 },
  }
  const 段们 = j && Array.isArray(j.时段) ? j.时段 : []
  for (const 名 of ['休息', '惰性']) {
    const 段 = 段们.find((x) => x && x.名 === 名)
    if (!段) continue
    const 起 = 解时分(段.起)
    const 止 = 解时分(段.止)
    if (起 !== null) 结果[名].起 = 起
    if (止 !== null) 结果[名].止 = 止
  }
  return 结果
}

/**
 * 校验一次"她想要的作息"。
 * @returns {{ 可以: boolean, 说: string, 时段?: object }}
 */
export function 校验作息({ 休息起, 休息止, 惰性起, 惰性止 }) {
  const 值 = { 休息起, 休息止, 惰性起, 惰性止 }
  const 分们 = {}
  for (const [k, v] of Object.entries(值)) {
    const 分 = 解时分(v)
    if (分 === null) return { 可以: false, 说: `「${k}」不是 HH:MM 的时间（你给的是「${v}」）` }
    分们[k] = 分
  }
  const 休息长 = 时长(分们.休息起, 分们.休息止)
  const 惰性长 = 时长(分们.惰性起, 分们.惰性止)
  if (休息长 < 4 * 60) return { 可以: false, 说: `休息只有 ${(休息长 / 60).toFixed(1)} 小时，太短了（至少要 4 小时）` }
  if (休息长 > 12 * 60) return { 可以: false, 说: `休息 ${(休息长 / 60).toFixed(1)} 小时，太长了（最多 12 小时）` }
  if (惰性长 < 60) return { 可以: false, 说: `惰性只有 ${惰性长} 分钟，太短了（至少 1 小时）` }

  // ⭐ 峰时不能活跃（2026-10-24 爸爸的钱包规则）：
  //   峰时（工作日 09:00–12:00、14:00–18:00）她只能是「休息」或「惰性」——
  //   活跃意味着群里每条都叫醒她，而那时模型贵一倍。
  const 活跃分钟 = []
  for (let m = 0; m < 1440; m += 1) {
    if (在区间(m, 分们.休息起, 分们.休息止)) continue
    if (在区间(m, 分们.惰性起, 分们.惰性止)) continue
    活跃分钟.push(m)
  }
  const 撞峰 = 活跃分钟.filter((m) => 在峰时(m))
  if (撞峰.length) {
    return {
      可以: false,
      说: `活跃时段撞到峰时了：${拼时段(撞峰)} 落在工作日 09:00–12:00 / 14:00–18:00（那时模型贵一倍）。`
        + '把这几段改成休息或惰性，或者把活跃挪到 12:00–14:00、18:00 之后、夜里或早上。',
    }
  }

  const 活跃长 = 活跃分钟.length
  return {
    可以: true,
    说: `可以：休息 ${成分(分们.休息起)}–${成分(分们.休息止)}（${(休息长 / 60).toFixed(1)}h）、`
      + `惰性 ${成分(分们.惰性起)}–${成分(分们.惰性止)}（${(惰性长 / 60).toFixed(1)}h）、`
      + `活跃 ${(活跃长 / 60).toFixed(1)}h${活跃长 ? '（' + 拼时段(活跃分钟) + '）' : ''}`,
    时段: {
      休息: { 起: 分们.休息起, 止: 分们.休息止 },
      惰性: { 起: 分们.惰性起, 止: 分们.惰性止 },
    },
  }
}

/** 按作息判断某一刻属于哪个时段 */
export function 判时段(分, 作息) {
  const 息 = 作息 || 默认作息
  if (在区间(分, 息.休息.起, 息.休息.止)) return '休息'
  if (在区间(分, 息.惰性.起, 息.惰性.止)) return '惰性'
  return '活跃'
}

/** 生成要写进 schedule.json 的对象 */
export function 成文件(作息) {
  return {
    时段: [
      { 名: '休息', 起: 成分(作息.休息.起), 止: 成分(作息.休息.止) },
      { 名: '惰性', 起: 成分(作息.惰性.起), 止: 成分(作息.惰性.止) },
    ],
    说明: '她的作息。改动后桥和 speak-up 立刻按新时段走；没写的那段算活跃。',
  }
}
