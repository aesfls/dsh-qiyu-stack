/**
 * 发送限速（防风控）—— 纯函数，方便单测
 *
 * 为什么要有这个：
 *   2026-10-24 部署出来的那个角色被封过一次号。查下来最吻合的是「行为频率」：
 *   群内动作最小间隔 0.37 秒、10 分钟 22 条、秒回零冷却。
 *   腾讯的社区协议端（NapCat / OneBot）判断「像不像机器」主要看这个，
 *   视频里那位也是在加上「冷却 + 间隔 + 夜里静默」之后才跑稳的。
 *
 * 设计：
 *   · 分「群 / 私聊」两条独立的队，互不影响
 *   · 一条消息发出去 → 记一笔时间
 *   · 下一条要发之前问「还要等多久」：没到间隔就睡，到点就放行
 *   · 每「成组」条之后加一段长的冷却（长串话说完歇口气）
 *
 * 另外给「收到消息 → 她开始回」加一点抖动（见 回复前等多久）：
 *   人是不会 0.2 秒就回的。
 */

/**
 * 档位（2026-10-25 定的，先走保守档）：
 *   单条间隔 4~10 秒，群聊私聊同时生效（先从保守的跑，稳了再谈放宽）。
 *   每 6 条歇 90 秒 —— 长串话说完必须停一下，这是风控最在意的那部分。
 */
export const 默认设置 = {
  'qq-group': { 最小间隔: 4000, 最大间隔: 10000, 成组: 6, 组间冷却: 90000 },
  'qq-private': { 最小间隔: 4000, 最大间隔: 10000, 成组: 6, 组间冷却: 90000 },
}

/**
 * 她在回话之前的「阅读时间」：收到消息后等 5~15 秒再让她开口。
 *
 * ⚠ 2026-10-25 11:05 修：这个函数 p31 版写了但**桥里没人调用**（死代码），
 *   等于没生效。现在接在 转入正文 的 followup 之前。
 *   为什么需要它：光有「发出去之间隔几秒」不够 —— 真正像机器的特征是
 *   **收到消息 0.2 秒就打字**。人要先看一眼、想一下。
 */
export const 回复前 = { 最短: 5000, 最长: 15000 }

/**
 * 取一条队的状态（没有就建一个）。
 * 状态很小，就三个数，没必要持久化——重启后重新开始计数是合理的。
 */
function 取队(状态, 键) {
  if (!状态[键]) 状态[键] = { 上次发出: -1, 本次间隔: 0, 组内已发: 0, 组冷却开始: -1 }
  return 状态[键]
}

/**
 * 「现在能不能发？不能的话还要等多久」——纯计算，不改状态。
 * @returns {number} 毫秒；0 = 现在就能发
 */
export function 还要等多久(状态, 键, 现在, 设置 = 默认设置) {
  const 该 = 设置[键]
  if (!该) return 0 // 没配的键不拦（比如别的 action）
  const 队 = 取队(状态, 键)

  // 0) 这条队还没发过任何东西 —— 第一条不用等
  if (队.上次发出 < 0) return 0

  // 1) 组间冷却还没走完（优先于单条间隔）
  if (队.组冷却开始 >= 0) {
    const 剩 = 队.组冷却开始 + 该.组间冷却 - 现在
    if (剩 > 0) return 剩
    // 冷却走完了：开新组，单条间隔从现在重新算（用最小间隔起步）
    队.组冷却开始 = -1
    队.组内已发 = 0
    队.本次间隔 = 该.最小间隔
  }

  // 2) 离上一条还不够（随机间隔由 记一笔 抽好放在 本次间隔 里）
  const 间隔 = 队.本次间隔 > 0 ? 队.本次间隔 : 该.最小间隔
  const 剩 = 队.上次发出 + 间隔 - 现在
  return 剩 > 0 ? 剩 : 0
}

/**
 * 真的发出去了一条：记账。
 * 顺手给「下一条」抽一个随机间隔（3~9 秒之间），让节奏不是恒定的。
 */
export function 记一笔(状态, 键, 现在, 设置 = 默认设置) {
  const 该 = 设置[键]
  if (!该) return
  const 队 = 取队(状态, 键)
  队.上次发出 = 现在
  队.本次间隔 = 抽间隔(该)
  队.组内已发 += 1
  if (队.组内已发 >= 该.成组) {
    // 发满一组：这段冷却从现在算起，并且组内计数归零
    队.组冷却开始 = 现在
    队.组内已发 = 0
  }
}

/** 在 [最小, 最大] 里抽一个整数毫秒 */
export function 抽间隔(该, 随机 = Math.random) {
  const 小 = Math.max(0, Number(该.最小间隔) || 0)
  const 大 = Math.max(小, Number(该.最大间隔) || 0)
  if (大 === 小) return 小
  return 小 + Math.floor(随机() * (大 - 小 + 1))
}

/** 收到消息到开始回之间要等多久（抖动，避免秒回） */
export function 回复前等多久(随机 = Math.random) {
  return 回复前.最短 + Math.floor(随机() * (回复前.最长 - 回复前.最短 + 1))
}

/**
 * 把「再等多久」写成她/日志看得懂的话。
 * 例：还剩 12 秒 →「12 秒后」
 */
export function 说多久(毫秒) {
  if (!毫秒 || 毫秒 <= 0) return '马上'
  const 秒 = Math.ceil(毫秒 / 1000)
  if (秒 < 60) return 秒 + ' 秒后'
  return Math.floor(秒 / 60) + ' 分 ' + (秒 % 60) + ' 秒后'
}
