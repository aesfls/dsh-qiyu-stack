/**
 * 扫一段话。
 * @returns {{ 命中: string[], 强: boolean, 该报: boolean }}
 */
export function 扫(文本) {
  const 文 = 归一(文本)
  if (!文) return { 命中: [], 强: false, 该报: false }
  const 命中 = 词表.filter((x) => x.式.test(文)).map((x) => x.名)
  const 强 = 词表.some((x) => x.强 && 命中.includes(x.名))
  return { 命中, 强, 该报: 强 || 命中.length >= 2 }
}
