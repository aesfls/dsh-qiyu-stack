import { pathToFileURL } from 'node:url'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

// 用绝对 file:// URL 导入（ESM 不认 Windows 的相对反斜杠路径，中文路径也容易踩坑）
const 这里 = dirname(fileURLToPath(import.meta.url))
const 模块 = pathToFileURL(resolve(这里, '..', 'runtime', 'bridge', 'lib', '限速.mjs')).href
const {
  还要等多久, 记一笔, 抽间隔, 回复前等多久, 说多久, 默认设置,
} = await import(模块)

let 过 = 0
let 败 = 0
function 断言(名, 条件, 细节) {
  if (条件) { 过++; return }
  败++
  console.log('  ✗ ' + 名 + (细节 ? '  → ' + 细节 : ''))
}

const 档 = 默认设置['qq-group']
const 固定 = () => 0.5 // 抽间隔永远取中点

console.log('== 1. 第一条不等 ==')
{
  const 状态 = {}
  断言('空状态立刻可发', 还要等多久(状态, 'qq-group', 1000) === 0)
}

console.log('== 2. 连发会被压住（核心：0.37 秒连发不再可能）==')
{
  const 状态 = {}
  记一笔(状态, 'qq-group', 1000)
  // ⚠ 这里必须读「记一笔 实际抽中的那个间隔」，不能在测试里再抽一次
  const 下条间隔 = 状态['qq-group'].本次间隔
  断言('间隔在 4000~10000 内', 下条间隔 >= 4000 && 下条间隔 <= 10000, '拿到 ' + 下条间隔)
  // 模拟“下一条 0.37 秒后就发”——应被拒绝
  const 等 = 还要等多久(状态, 'qq-group', 1000 + 370)
  断言('0.37 秒后要等', 等 > 0, '等 ' + 等)
  断言('至少要等到最小间隔附近', 等 >= 下条间隔 - 370 - 1, '等 ' + 等 + ' 间隔 ' + 下条间隔)
  // 差 1 毫秒还不放行，到点才放行
  断言('差 1ms 仍拦', 还要等多久(状态, 'qq-group', 1000 + 下条间隔 - 1) === 1)
  断言('等够就放行', 还要等多久(状态, 'qq-group', 1000 + 下条间隔) === 0)
}

console.log('== 3. 成组与组间冷却 ==')
{
  const 状态 = {}
  let t = 0
  for (let i = 0; i < 档.成组; i++) {
    记一笔(状态, 'qq-group', t)
    t += 状态['qq-group'].本次间隔 + 1
  }
  // 发满 6 条 → 应进入冷却
  const 等 = 还要等多久(状态, 'qq-group', t)
  断言('第 6 条之后进冷却', 等 > 0, '等 ' + 等)
  断言('冷却至少 60 秒', 等 >= 60000, '等 ' + 等)
  // 冷却到点 → 放行，并且重新计数
  断言('冷却到点放行', 还要等多久(状态, 'qq-group', t + 档.组间冷却) === 0)
  记一笔(状态, 'qq-group', t + 档.组间冷却)
  const 队 = 状态['qq-group']
  断言('新组重新计数', 队.组内已发 === 1, '组内 ' + 队.组内已发)
}

console.log('== 4. 群、私聊两条队互不影响 ==')
{
  const 状态 = {}
  记一笔(状态, 'qq-group', 1000)
  断言('群发了私聊不受影响', 还要等多久(状态, 'qq-private', 1000) === 0)
  记一笔(状态, 'qq-private', 1000)
  断言('私聊也压住', 还要等多久(状态, 'qq-private', 1100) > 0)
  断言('群仍然单独计算', 还要等多久(状态, 'qq-group', 1100) > 0)
}

console.log('== 5. 没配的键不拦（别误伤别的 action）==')
{
  const 状态 = {}
  记一笔(状态, 'qq-group', 1000)
  断言('未配置的键放行', 还要等多久(状态, '别的键', 1000) === 0)
}

console.log('== 6. 间隔是随机的，不是恒定值 ==')
{
  const 值 = new Set()
  for (let i = 0; i < 200; i++) 值.add(抽间隔(档))
  断言('至少产生 20 种不同间隔', 值.size >= 20, '只有 ' + 值.size + ' 种')
  const 全 = [...值]
  断言('全部落在 4000~10000', 全.every((v) => v >= 4000 && v <= 10000))
}

console.log('== 7. 阅读时间（收到消息到她开口之间）==')
{
  const 值 = new Set()
  for (let i = 0; i < 200; i++) 值.add(回复前等多久())
  断言('至少 20 种', 值.size >= 20, '只有 ' + 值.size + ' 种')
  断言('落在 5000~15000', [...值].every((v) => v >= 5000 && v <= 15000))
}

console.log('== 8. 说多久 的文案 ==')
{
  断言('0 → 马上', 说多久(0) === '马上')
  断言('12000 → 12 秒后', 说多久(12000) === '12 秒后', 说多久(12000))
  断言('90000 → 1 分 30 秒后', 说多久(90000) === '1 分 30 秒后', 说多久(90000))
}

console.log('== 9. 长串不会把状态搞坏（并发/异常输入）==')
{
  const 状态 = {}
  for (let i = 0; i < 500; i++) 记一笔(状态, 'qq-group', i * 10000)
  const 队 = 状态['qq-group']
  断言('组内计数不会超界成负数', 队.组内已发 >= 0 && 队.组内已发 < 档.成组, '组内 ' + 队.组内已发)
  断言('没有 NaN', Number.isFinite(队.上次发出) && Number.isFinite(队.组冷却开始))
}

console.log('')
console.log(败 === 0 ? `全部通过：${过}/${过}` : `失败 ${败} / 共 ${过 + 败}`)
process.exit(败 === 0 ? 0 : 1)
