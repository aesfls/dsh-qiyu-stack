/**
 * 回归测试：p34「刚醒来说分不出来源」
 *
 * 复现 2026-10-25 11:27 的真实故障：
 *   主人私聊一句「这是一条QQ消息，嘻嘻」，她回「我这边分不出来源，标签上没写」。
 *   日志顺序：11:26:53 "目标会话本来没醒着，QQ 这条把它叫醒了" → 11:27:08 "收到 1 条，用时 14.9 秒"
 *   根因：p32/p33 的阅读时间排在**叫醒之后**，她醒来时手里什么都没有，空转 15 秒。
 *
 * 还测两件事：
 *   · 叫醒失败时，被 打包攒消息() 取走的消息必须**还回去**（那是不可逆的副作用）
 *   · followup 失败时也一样
 *
 * 不连 QQ、不起桥，纯时序验证。
 * 跑法（在本仓库根目录）：node test\p34-来源.test.mjs
 */

let 过 = 0, 败 = 0
function 断言(名, 条件, 细节) {
  if (条件) { 过++; return }
  败++
  console.log('  ✗ ' + 名 + (细节 ? '  → ' + 细节 : ''))
}

const 睡 = (ms) => new Promise((r) => setTimeout(r, ms))

/** 造一个和 host.js 同构的时间线记录器 */
function 造世界(选项 = {}) {
  const { 阅读 = 20, 会话活着 = false, 叫醒成功 = true, followup抛错 = false } = 选项
  const 时间线 = []          // [{t, 事件}]
  const 起 = Date.now()
  const 记 = (事件) => 时间线.push({ t: Date.now() - 起, 事件 })
  let 攒消息 = [{ 行: '[群] 某某: 早上好' }]
  let 攒的是哪个时段的 = '休息'
  let 会话醒着 = 会话活着

  // 与 host.js 同构的 打包攒消息（有副作用：取走就清空）
  const 打包攒消息 = () => {
    if (!攒消息.length) return { 文本: '', 含群: false }
    const 正文 = 攒消息.map((x, i) => `${i + 1}. ${x.行}`).join('\n')
    const 含群 = 攒消息.some((x) => !x.是私聊)
    攒消息 = []
    攒的是哪个时段的 = ''
    return { 文本: `（一起给你（共 1 条）：\n\n${正文}）`, 含群 }
  }

  async function 转入正文(文字, 标签, uid) {
    let 全文 = 标签 ? `[${标签}] ${文字}` : 文字
    const 攒的原样 = { 攒消息, 时段: 攒的是哪个时段的 }
    const 打包 = 打包攒消息()
    const 有打包 = !!打包.文本
    const 还回攒消息 = () => {
      if (!有打包) return
      攒消息 = 攒的原样.攒消息
      攒的是哪个时段的 = 攒的原样.时段
      记('还回攒消息')
    }
    if (有打包) 全文 = 打包.文本 + '\n\n' + 全文
    const 来源种类 = uid ? 'qq-private' : 'qq-group'

    // ── p34：阅读时间在叫醒之前 ──
    记('开始阅读等待')
    await 睡(有打包 ? Math.min(阅读, 5) : 阅读)
    记('阅读等待结束')
    断言('等待期间会话应该是睡着的', !会话醒着, '会话提前醒了')

    // 叫醒
    if (!会话醒着) {
      if (叫醒成功) {
        会话醒着 = true
        记('叫醒成功')
      } else {
        记('叫醒失败')
      }
    }
    if (!会话醒着) {
      还回攒消息()
      return { ok: false, 说: '目标会话现在没活着' }
    }

    // 第一次喂给 agent
    记({ 喂: 全文, 来源: 来源种类 })
    try {
      if (followup抛错) throw new Error('模拟 followup 失败')
      记('followup 成功')
      return { ok: true }
    } catch (e) {
      还回攒消息()
      return { ok: false, 说: 'followup 失败' }
    }
  }

  return { 时间线, 转入正文, 拿攒: () => 攒消息, 记 }
}

console.log('== 1. 关键顺序：等待 → 叫醒 → 喂（中间不能有空档）==')
{
  const 世界 = 造世界({ 阅读: 20 })
  await 世界.转入正文('这是一条QQ消息，嘻嘻', '主人', 1)
  const 顺序 = 世界.时间线.map((x) => (typeof x.事件 === 'string' ? x.事件 : '喂给agent'))
  断言('先等再醒', 顺序.indexOf('开始阅读等待') < 顺序.indexOf('叫醒成功'), 顺序.join(' → '))
  断言('醒后立刻喂', 顺序.indexOf('叫醒成功') < 顺序.indexOf('喂给agent'), 顺序.join(' → '))
  // 叫醒和喂之间不能有别的耗时动作
  const 醒 = 世界.时间线.find((x) => x.事件 === '叫醒成功')
  const 喂 = 世界.时间线.find((x) => typeof x.事件 === 'object')
  断言('叫醒到喂之间 < 5ms', 喂.t - 醒.t < 5, '差了 ' + (喂.t - 醒.t) + 'ms')
  console.log('   → ' + 顺序.join(' → '))
}

console.log('== 2. 她第一眼看到的消息必须带来源标签 ==')
{
  for (const [名, 标签, uid, 期望] of [
    ['私聊', '主人', 1, 'qq-private'],
    ['群聊', undefined, undefined, 'qq-group'],
  ]) {
    const 世界 = 造世界({ 阅读: 10 })
    await 世界.转入正文('你好', 标签, uid)
    const 第一次喂 = 世界.时间线.find((x) => typeof x.事件 === 'object')
    断言(名 + ' 第一次喂带来源', 第一次喂 && 第一次喂.事件.来源 === 期望, JSON.stringify(第一次喂 && 第一次喂.事件))
    断言(名 + ' 正文带名字前缀', !标签 || 第一次喂.事件.喂.includes(`[${标签}]`), 第一次喂.事件.喂.slice(0, 30))
  }
}

console.log('== 3. 叫醒失败 → 攒消息必须还回去（不能丢）==')
{
  const 世界 = 造世界({ 阅读: 5, 叫醒成功: false })
  const r = await 世界.转入正文('你好', '主人', 1)
  断言('返回失败', r.ok === false)
  断言('攒消息还回来了', 世界.拿攒().length === 1, '现在 ' + 世界.拿攒().length + ' 条')
  断言('时间线里有「还回」', 世界.时间线.some((x) => x.事件 === '还回攒消息'))
}

console.log('== 4. followup 失败 → 也要还回去 ==')
{
  const 世界 = 造世界({ 阅读: 5, followup抛错: true })
  const r = await 世界.转入正文('你好', '主人', 1)
  断言('返回失败', r.ok === false)
  断言('攒消息还回来了', 世界.拿攒().length === 1, '现在 ' + 世界.拿攒().length + ' 条')
}

console.log('== 5. 成功时不该乱还（攒消息该被消费掉）==')
{
  const 世界 = 造世界({ 阅读: 5 })
  const r = await 世界.转入正文('你好', '主人', 1)
  断言('返回成功', r.ok === true)
  断言('攒消息已消费', 世界.拿攒().length === 0, '还剩 ' + 世界.拿攒().length + ' 条')
  断言('没有误还', !世界.时间线.some((x) => x.事件 === '还回攒消息'))
}

console.log('')
console.log(败 === 0 ? `全部通过：${过}/${过}` : `失败 ${败} / 共 ${过 + 败}`)
process.exit(败 === 0 ? 0 : 1)
